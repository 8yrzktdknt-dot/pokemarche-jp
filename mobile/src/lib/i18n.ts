/** Langues de l'interface (et des noms de cartes et d'extensions quand ils sont traduits). */
export type AppLang = 'fr' | 'en' | 'ja' | 'zh-tw' | 'zh-cn' | 'es' | 'it' | 'de' | 'nl' | 'pt' | 'ru' | 'th' | 'ko';
